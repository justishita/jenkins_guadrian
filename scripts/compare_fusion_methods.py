"""Compare the two fusion methods (noisy-OR vs weighted mean) on the stated criteria.

**Owner:** P2. Usage::

    python scripts/compare_fusion_methods.py            # print the report
    python scripts/compare_fusion_methods.py --write    # also write docs/fusion_method_comparison.md

Criteria (decided before looking at results, see the Week 4 plan):
  (a) top-1 correctness against the labelled coordinator scenarios,
  (b) ranking quality (reciprocal rank of the labelled type),
  (c) sensitivity to overlapping evidence (two agents reading the same failure),
  (d) behaviour with missing, failed and conflicting agents,
  (e) monotonicity: an additional agreeing vote must never lower a score.

"Scores went up when agents agree" is deliberately not a criterion. The labelled scenarios are
few and author-written, so this can show a method behaves badly; it cannot show one is
generally better. The script reports that limit with its numbers.
"""

from __future__ import annotations

import argparse
import sys
from itertools import product
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from coordinator.fusion import noisy_or, weighted_mean
from coordinator.report import FusionMethod
from tests.coordinator.scenario_runner import (
    load_coordinator_scenarios,
    run_scenario,
)

METHODS = (FusionMethod.NOISY_OR, FusionMethod.WEIGHTED_MEAN)


def accuracy(scenarios: list[dict], method: FusionMethod) -> tuple[int, int, float, list[str]]:
    labelled = [s for s in scenarios if s.get("truth")]
    hits, reciprocal, misses = 0, 0.0, []
    for scenario in labelled:
        report = run_scenario(scenario, method)
        ranked = [r.failure_type.value for r in report.ranking]
        if report.verdict.value == scenario["truth"]:
            hits += 1
        else:
            misses.append(f"{scenario['id']} (got {report.verdict.value}, truth {scenario['truth']})")
        if scenario["truth"] in ranked:
            reciprocal += 1 / (ranked.index(scenario["truth"]) + 1)
        elif scenario["truth"] == "unknown" and not ranked:
            reciprocal += 1.0
    return hits, len(labelled), reciprocal / len(labelled), misses


def monotonicity_violations() -> dict[FusionMethod, tuple[int, int]]:
    """Add a second, supporting vote to a single vote; count cases where the score drops."""
    grid = [round(0.1 * i, 1) for i in range(1, 10)]
    relevance = [0.3, 0.6, 1.0]
    result = {m: [0, 0] for m in METHODS}
    for c1, c2, w1, w2 in product(grid, grid, relevance, relevance):
        one = [c1 * w1]
        two = [c1 * w1, c2 * w2]
        scores = {
            FusionMethod.NOISY_OR: (noisy_or(one), noisy_or(two)),
            FusionMethod.WEIGHTED_MEAN: (weighted_mean(one, [w1]), weighted_mean(two, [w1, w2])),
        }
        for method, (before, after) in scores.items():
            result[method][1] += 1
            if after < before - 1e-12:
                result[method][0] += 1
    return {m: (v[0], v[1]) for m, v in result.items()}


def overlap_inflation() -> dict[FusionMethod, float]:
    """Two agents that read the SAME failure at the same confidence vs one agent: score ratio.

    1.0 means a second, fully redundant source adds nothing; larger means it is rewarded as if
    independent. Evaluated at confidence 0.6, relevance 1.0.
    """
    one, two = [0.6], [0.6, 0.6]
    return {
        FusionMethod.NOISY_OR: noisy_or(two) / noisy_or(one),
        FusionMethod.WEIGHTED_MEAN: weighted_mean(two, [1, 1]) / weighted_mean(one, [1]),
    }


def degraded(scenarios: list[dict]) -> list[tuple[str, dict[FusionMethod, str]]]:
    wanted = {"coord-partial-reporting", "coord-failed-agent", "coord-conflict-close", "coord-corroboration-vs-single"}
    rows = []
    for scenario in scenarios:
        if scenario["id"] in wanted:
            rows.append(
                (
                    scenario["id"],
                    {m: f"{run_scenario(scenario, m).verdict.value} {run_scenario(scenario, m).confidence:.2f}" for m in METHODS},
                )
            )
    return rows


def disagreements(scenarios: list[dict]) -> int:
    return sum(
        1
        for s in scenarios
        if s.get("truth") and run_scenario(s, METHODS[0]).verdict != run_scenario(s, METHODS[1]).verdict
    )


def build_report() -> str:
    scenarios = load_coordinator_scenarios()
    lines = ["# Fusion method comparison (noisy-OR vs weighted mean)", "", "Generated by `python scripts/compare_fusion_methods.py --write`.", ""]

    lines += ["## (a) and (b) Accuracy on the labelled scenarios", "", "| Method | Top-1 correct | Mean reciprocal rank | Misses |", "|---|---|---|---|"]
    for method in METHODS:
        hits, total, mrr, misses = accuracy(scenarios, method)
        lines.append(f"| {method.value} | {hits}/{total} | {mrr:.2f} | {'; '.join(misses) or 'none'} |")

    violations = monotonicity_violations()
    lines += ["", "## (e) Monotonicity: adding a supporting vote must not lower the score", "", "| Method | Violations | Cases |", "|---|---|---|"]
    for method in METHODS:
        bad, total = violations[method]
        lines.append(f"| {method.value} | {bad} | {total} |")

    inflation = overlap_inflation()
    lines += [
        "",
        "## (c) Overlapping evidence: two agents, same failure, confidence 0.60 each",
        "",
        "| Method | Score with 2 sources / score with 1 |",
        "|---|---|",
    ]
    for method in METHODS:
        lines.append(f"| {method.value} | {inflation[method]:.2f} |")
    lines += [
        "",
        (
            "Noisy-OR treats a second source as independent confirmation, so redundant sources are "
            "over-rewarded (the agents here can read overlapping evidence: Code and Jenkins both see "
            "the same commit's effects). The weighted mean ignores a redundant source, but also "
            "ignores genuine independent confirmation."
        ),
    ]

    lines += ["", "## (d) Missing, failed and conflicting agents", "", "| Scenario | noisy_or | weighted_mean |", "|---|---|---|"]
    for scenario_name, results in degraded(scenarios):
        lines.append(f"| {scenario_name} | {results[FusionMethod.NOISY_OR]} | {results[FusionMethod.WEIGHTED_MEAN]} |")

    labelled = sum(1 for s in scenarios if s.get("truth"))
    lines += [
        "",
        "## Limits of this comparison",
        "",
        (
            f"- Only {labelled} scenarios carry a label, written by the author. A method can win on them "
            "without being generally better, and the labels encode the author's view that independent "
            "corroboration should beat one stronger source."
        ),
        (
            f"- The methods disagree on the verdict in {disagreements(scenarios)} labelled scenario(s); "
            "the accuracy gap above rests on that many cases, so the monotonicity and overlap results "
            "carry more weight than the accuracy numbers."
        ),
        "- Neither method is calibrated: scores order hypotheses; they are not probabilities.",
        "",
        "## Decision",
        "",
        (
            "Provisional: **noisy-OR**, labelled uncalibrated. It is the only method that is monotone "
            "(corroboration never lowers a score) and it is the only one that can express independent "
            "agreement, which is the point of three agents with different evidence domains. Its known "
            "weakness is over-rewarding overlapping evidence; the bounded relevance weights and the "
            "capped negative evidence limit but do not remove that. Every report records the "
            "weighted-mean score alongside, so the choice can be revisited with real labelled incidents."
        ),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write docs/fusion_method_comparison.md")
    args = parser.parse_args()
    text = build_report()
    print(text)
    if args.write:
        (REPO / "docs" / "fusion_method_comparison.md").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
